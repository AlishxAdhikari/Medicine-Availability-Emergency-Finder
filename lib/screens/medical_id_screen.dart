  Widget _buildQRSection(
    BuildContext context,
    UserProfile profile,
    bool isDark,
  ) {
    final theme = Theme.of(context);
    // Encoded once per build and shared by the code itself and the download
    // button below, so the payload is not built and bit-packed three times
    // on every rebuild of this card.
    final payload = _buildEmergencyPayload(profile);
    final fitsInQr = _fitsInQrCode(payload);
    return Container(
      decoration: _cardDeco(isDark),
      padding: const EdgeInsets.all(16),
      child: Column(
        children: [
          Row(
            children: [
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                decoration: BoxDecoration(
                  color: const Color(0xFFBA1A1A).withValues(alpha: 0.1),
                  borderRadius: BorderRadius.circular(6),
                ),
                child: const Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Icon(Icons.emergency, size: 12, color: Color(0xFFBA1A1A)),
                    SizedBox(width: 4),
                    Text(
                      'EMERGENCY QR',
                      style: TextStyle(
                        fontSize: 10,
                        fontWeight: FontWeight.w800,
                        color: Color(0xFFBA1A1A),
                        letterSpacing: 0.5,
                      ),
                    ),
                  ],
                ),
              ),
              const Spacer(),
              Text(
                'Scan offline',
                style: TextStyle(
                  fontSize: 11,
                  color: theme.colorScheme.onSurfaceVariant,
                ),
              ),
            ],
          ),
          const SizedBox(height: 14),
          RepaintBoundary(
            key: _qrBoundaryKey,
            child: Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: Colors.white,
                borderRadius: BorderRadius.circular(14),
                border: Border.all(color: const Color(0xFFE5E9F0)),
                boxShadow: [
                  BoxShadow(
                    color: Colors.black.withValues(alpha: 0.05),
                    blurRadius: 12,
                    offset: const Offset(0, 4),
                  ),
                ],
              ),
              child: !fitsInQr
                  ? _qrTooLong(context)
                  : QrImageView(
                      data: payload,
                      version: QrVersions.auto,
                      errorCorrectionLevel: QrErrorCorrectLevel.M,
                      size: 160,
                      backgroundColor: Colors.white,
                      // A QR code tops out around 2.3 KB at this correction level,
                      // and the payload grows with every allergy, medication and
                      // emergency contact -- none of which the editor caps. Without
                      // this builder qr_flutter throws QrInputTooLongException
                      // during build, which takes down the whole Medical ID tab.
                      //
                      // Deliberately not truncating the payload to make it fit: a
                      // silently dropped allergy is exactly the failure this screen
                      // exists to prevent. Better to show nothing and say why, so
                      // the user shortens it themselves.
                      // Kept as a second line of defence for the other failure
                      // modes validate() does catch.
                      errorStateBuilder: (context, _) => _qrTooLong(context),
                    ),
            ),
          ),
          const SizedBox(height: 10),
          Text(
            'ID · vitals · allergies · meds · contacts',
            style: TextStyle(
              fontSize: 11,
              color: theme.colorScheme.onSurfaceVariant,
              fontStyle: FontStyle.italic,
            ),
            textAlign: TextAlign.center,
          ),
          const SizedBox(height: 12),
          SizedBox(
            width: double.infinity,
            height: 42,
            child: OutlinedButton.icon(
              // Disabled when there is no code to share: the repaint boundary
              // would otherwise capture the "too long" message and hand the
              // user a PNG of an error notice.
              onPressed: _isDownloading || !fitsInQr
                  ? null
                  : () => _downloadQrCode(profile),
              icon: _isDownloading
                  ? SizedBox(
                      width: 15,
                      height: 15,
                      child: CircularProgressIndicator(
                        strokeWidth: 2,
                        color: theme.colorScheme.primary,
                      ),
                    )
                  : const Icon(Icons.download_rounded, size: 17),
              label: Text(
                _isDownloading ? 'Preparing…' : 'Download QR',
                style: const TextStyle(
                  fontWeight: FontWeight.w700,
                  fontSize: 13,
                ),
              ),
              style: OutlinedButton.styleFrom(
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(11),
                ),
              ),
            ),
          ),
        ],
      ),
    );
  }

