  String _buildEmergencyPayload(UserProfile profile) {
    final buffer = StringBuffer()
      ..writeln('MEDALERT EMERGENCY MEDICAL ID')
      ..writeln('--------------------------------');

    if (profile.medicalId.isNotEmpty) {
      buffer.writeln('Medical ID: ${profile.medicalId}');
    }

    buffer
      ..writeln('Name: ${profile.fullName}')
      ..writeln(
        'Gender: ${profile.gender.isNotEmpty ? profile.gender : 'Not specified'}',
      )
      ..writeln('DOB: ${profile.dob}')
      ..writeln(
        'Phone: ${profile.phoneNumber.isNotEmpty ? profile.phoneNumber : 'Not specified'}',
      )
      ..writeln(
        'Blood Group: ${profile.bloodGroup.isNotEmpty ? profile.bloodGroup : 'Not specified'}',
      );

    if (profile.height.trim().isNotEmpty) {
      buffer.writeln('Height: ${profile.height} cm');
    }
    if (profile.weight.trim().isNotEmpty) {
      buffer.writeln('Weight: ${profile.weight} kg');
    }
    if (profile.address.trim().isNotEmpty) {
      buffer.writeln('Address: ${profile.address}');
    }

    buffer.writeln(
      'SEVERE ALLERGIES: ${profile.allergies.isEmpty ? 'None reported' : profile.allergies.join(', ')}',
    );

    if (profile.medications.isNotEmpty) {
      final meds = profile.medications
          .map((m) => '${m.name} ${m.dosage} (${m.frequency})')
          .join('; ');
      buffer.writeln('Medications: $meds');
    }

    if (profile.emergencyContacts.isNotEmpty) {
      buffer.writeln('--------------------------------');
      buffer.writeln('Emergency Contacts:');
      for (final contact in profile.emergencyContacts) {
        buffer.writeln(
          '${contact.name} (${contact.relationship}) - ${contact.phoneNumber}',
        );
      }
    }

    buffer.write(
      '--------------------------------\nGenerated by MedAlert Nepal',
    );
    return buffer.toString();
  }

  /// Whether [data] actually fits in a QR code at the settings below.
  ///
  /// Necessary because QrImageView's own `errorStateBuilder` never fires for
  /// this case: QrValidator.validate reports oversized input as *valid*
  /// (qr 3.0.2 builds the code lazily, so nothing has counted the bits yet),
  /// and the InputTooLongException is thrown later from QrPainter during
  /// paint -- past the point the builder covers, so it takes the tab down.
  /// Building a QrImage from the code here forces that work to happen where
  /// it can be caught -- that is the step that actually fills the bit buffer
  /// and compares it against the version's capacity.
  bool _fitsInQrCode(String data) {
    try {
      QrImage(
        QrCode.fromData(data: data, errorCorrectLevel: QrErrorCorrectLevel.M),
      );
      return true;
    } catch (_) {
      return false;
    }
  }

  /// Shown in place of the QR when the profile no longer fits in one.
  ///
  /// Sized to match the QR it replaces so the card does not jump, and worded
  /// as an instruction rather than an error because the fix is entirely in
  /// the user's hands: shorten the medication or allergy text, or remove an
  /// emergency contact.
  Widget _qrTooLong(BuildContext context) {
    return SizedBox(
      width: 160,
      height: 160,
      child: Padding(
        padding: const EdgeInsets.all(8),
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          mainAxisSize: MainAxisSize.min,
          children: [
            const Icon(
              Icons.qr_code_2_outlined,
              size: 28,
              color: Colors.black54,
            ),
            const SizedBox(height: 6),
            // Flexible so the message shrinks into the QR's footprint instead
            // of overflowing it -- the surrounding card is a fixed 160px and
            // an overflow stripe here would look like a rendering bug on a
            // screen a responder is meant to trust.
            Flexible(
              child: Text(
                'Profile too long for an offline QR code. Shorten your '
                'medications or allergies.',
                textAlign: TextAlign.center,
                style: Theme.of(context).textTheme.bodySmall?.copyWith(
                  color: Colors.black87,
                  fontSize: 10,
                  height: 1.25,
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }

  /// The rectangle iPad anchors the share popover to: the QR code itself, in
  /// global coordinates, so the sheet points at the thing being shared.
  ///
  /// Falls back to the centre of the screen when the boundary has gone (a
  /// rebuild mid-share), and to a 1x1 rect at the origin when even that is
  /// unavailable -- an arbitrary but valid anchor beats throwing, because on
  /// iPhone and Android the value is ignored entirely.
  Rect _shareOrigin() {
    final box = _qrBoundaryKey.currentContext?.findRenderObject() as RenderBox?;
    if (box != null && box.hasSize) {
      return box.localToGlobal(Offset.zero) & box.size;
    }
    final size = MediaQuery.maybeOf(context)?.size;
    if (size != null) {
      return Rect.fromCenter(
        center: Offset(size.width / 2, size.height / 2),
        width: 1,
        height: 1,
      );
    }
    return const Rect.fromLTWH(0, 0, 1, 1);
  }

  Future<void> _downloadQrCode(UserProfile profile) async {
    if (_isDownloading) return;
    setState(() => _isDownloading = true);

    try {
      final boundary =
          _qrBoundaryKey.currentContext?.findRenderObject()
              as RenderRepaintBoundary?;
      if (boundary == null) {
        throw Exception('QR code is not ready yet');
      }

      final image = await boundary.toImage(pixelRatio: 3.0);
      final byteData = await image.toByteData(format: ui.ImageByteFormat.png);
      if (byteData == null) {
        throw Exception('Could not encode QR code image');
      }
      final bytes = byteData.buffer.asUint8List();

      final xFile = XFile.fromData(
        bytes,
        name: 'medalert_medical_id_qr.png',
        mimeType: 'image/png',
      );

      if (!mounted) return;
      await Share.shareXFiles(
        [xFile],
        text: 'My MedAlert emergency medical ID',
        // Required on iPad, where the share sheet is a popover that UIKit
        // anchors to a rectangle instead of sliding up from the bottom.
        // Omitting it throws PlatformException(sharePositionOrigin), which
        // this screen then reported as "could not generate QR code" -- the
        // image was fine, only the sheet failed to open.
        sharePositionOrigin: _shareOrigin(),
      );
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          // The QR is rendered and encoded before we get here, so a failure
          // at this point is the share sheet, not the code itself. Saying
          // "could not generate" sent us looking in the wrong place.
          SnackBar(content: Text('Could not share the QR code: $e')),
        );
      }
    } finally {
      if (mounted) setState(() => _isDownloading = false);
    }
  }

  String _display(String value, [String fallback = 'Not set']) {
    final t = value.trim();
    return t.isEmpty ? fallback : t;
  }

